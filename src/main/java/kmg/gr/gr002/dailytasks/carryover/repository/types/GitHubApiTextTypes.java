package kmg.gr.gr002.dailytasks.carryover.repository.types;

import java.util.HashMap;
import java.util.Map;

import kmg.core.infrastructure.cmn.KmgCmnTypes;

/**
 * GitHub API の固定文字列<br>
 *
 * @author KenichiroArai
 *
 * @since 0.1.0
 *
 * @version 0.1.0
 */
@SuppressWarnings("nls")
public enum GitHubApiTextTypes implements KmgCmnTypes<String> {

    /* 定義：開始 */

    /** 指定無し */
    NONE("指定無し", "None", "指定無し", null),

    /** 空文字 */
    EMPTY("空文字", "Empty", "項目がない場合の空文字", ""),

    /* 定義：終了 */
    ;

    /** 種類のマップ */
    private static final Map<String, GitHubApiTextTypes> VALUES_MAP = new HashMap<>();

    static {

        /* 種類のマップにプット */
        for (final GitHubApiTextTypes type : GitHubApiTextTypes.values()) {

            GitHubApiTextTypes.VALUES_MAP.put(type.get(), type);

            if (type.getText() != null) {

                GitHubApiTextTypes.VALUES_MAP.put(type.getText(), type);

            }

        }

    }

    /**
     * デフォルトの種類を返す<br>
     *
     * @return デフォルト値
     */
    public static GitHubApiTextTypes getDefault() {

        final GitHubApiTextTypes result = NONE;
        return result;

    }

    /**
     * キーに該当する種類を返す<br>
     * <p>
     * 但し、キーが存在しない場合は、指定無し（NONE）を返す。
     * </p>
     *
     * @param key
     *            キー
     *
     * @return 種類。指定無し（NONE）：キーが存在しない場合。
     */
    public static GitHubApiTextTypes getEnum(final String key) {

        GitHubApiTextTypes result = GitHubApiTextTypes.VALUES_MAP.get(key);

        if (result == null) {

            result = NONE;

        }
        return result;

    }

    /**
     * 初期値の種類を返す<br>
     *
     * @return 初期値
     */
    public static GitHubApiTextTypes getInitValue() {

        final GitHubApiTextTypes result = NONE;
        return result;

    }

    /** 表示名 */
    private final String displayName;

    /** キー */
    private final String key;

    /** 詳細情報 */
    private final String detail;

    /** 文字列 */
    private final String text;

    /**
     * コンストラクタ<br>
     *
     * @param displayName
     *                    表示名
     * @param key
     *                    キー
     * @param detail
     *                    詳細情報
     * @param text
     *                    文字列
     */
    GitHubApiTextTypes(final String displayName, final String key, final String detail, final String text) {

        this.displayName = displayName;
        this.key = key;
        this.detail = detail;
        this.text = text;

    }

    /**
     * キーを返す。<br>
     *
     * @return キー
     *
     * @see #getKey()
     */
    @Override
    public String get() {

        final String result = this.getKey();
        return result;

    }

    /**
     * 詳細情報を返す。<br>
     *
     * @return 詳細情報
     */
    @Override
    public String getDetail() {

        final String result = this.detail;
        return result;

    }

    /**
     * 表示名を返す。<br>
     * <p>
     * 識別するための表示名を返す。
     * </p>
     *
     * @return 表示名
     */
    @Override
    public String getDisplayName() {

        final String result = this.displayName;
        return result;

    }

    /**
     * 文字列を返す。<br>
     *
     * @return 文字列
     */
    public String getText() {

        final String result = this.text;
        return result;

    }

    /**
     * キーを返す。<br>
     *
     * @return キー
     */
    @Override
    public String getKey() {

        final String result = this.key;
        return result;

    }

    /**
     * キーを返す。<br>
     *
     * @return キー
     *
     * @see #getKey()
     */
    @Override
    public String toString() {

        final String result = this.getKey();
        return result;

    }

}
